"""Sales Performance Dashboard (Streamlit version).

Data is synthetic: generated by code with a fixed random seed (no dataset download).
Run locally:  streamlit run app.py
"""
import sqlite3

import numpy as np
import pandas as pd
import plotly.graph_objects as go
import streamlit as st
from scipy import stats

st.set_page_config(page_title="Sales Performance Dashboard", page_icon="📊", layout="wide")


# ----------------------------------------------------------------------------
# 1. Data (synthetic, reproducible)
# ----------------------------------------------------------------------------
@st.cache_data(show_spinner="Generating dataset...")
def generate_data(n=15000, seed=42):
    rng = np.random.default_rng(seed)
    regions = ["North", "South", "East", "West", "Central"]
    region_weight = np.array([1.00, 1.20, 0.80, 1.10, 0.70])
    region_weight = region_weight / region_weight.sum()

    catalog = {
        "Technology": {"products": ["Laptop", "Phone", "Tablet", "Monitor", "Headphones"],
                       "price": (150, 900), "margin": 0.18},
        "Furniture": {"products": ["Chair", "Desk", "Bookcase", "Sofa", "Cabinet"],
                      "price": (80, 600), "margin": 0.10},
        "Office Supplies": {"products": ["Paper", "Binder", "Pens", "Stapler", "Labels"],
                            "price": (3, 60), "margin": 0.25},
    }
    segments = ["Consumer", "Corporate", "Home Office"]
    season = {1: .8, 2: .8, 3: .9, 4: .95, 5: 1.0, 6: 1.0,
              7: .95, 8: 1.0, 9: 1.05, 10: 1.1, 11: 1.4, 12: 1.5}
    year_growth = {2023: 1.0, 2024: 1.08, 2025: 1.15}

    days = pd.date_range("2023-01-01", "2025-12-31")
    day_w = np.array([season[d.month] * year_growth[d.year] for d in days])
    day_w = day_w / day_w.sum()
    order_dates = rng.choice(days, size=n, p=day_w)

    rows = []
    cat_names = list(catalog.keys())
    cat_probs = [0.25, 0.20, 0.55]
    for i in range(n):
        cat = rng.choice(cat_names, p=cat_probs)
        info = catalog[cat]
        lo, hi = info["price"]
        unit_price = round(rng.uniform(lo, hi), 2)
        qty = int(rng.integers(1, 8))
        discount = float(rng.choice([0, 0.05, 0.10, 0.20, 0.30], p=[.45, .2, .15, .12, .08]))
        sales = qty * unit_price * (1 - discount)
        profit = sales * (info["margin"] - 0.9 * discount + rng.normal(0, 0.03))
        rows.append({
            "order_id": f"ORD-{100000 + i}",
            "order_date": order_dates[i],
            "region": rng.choice(regions, p=region_weight),
            "category": cat,
            "product": rng.choice(info["products"]),
            "segment": rng.choice(segments, p=[.55, .30, .15]),
            "quantity": qty,
            "unit_price": unit_price,
            "discount": discount,
            "sales": round(sales, 2),
            "profit": round(profit, 2),
        })

    df = pd.DataFrame(rows)
    df["order_date"] = pd.to_datetime(df["order_date"])
    df = df.drop_duplicates("order_id")
    df = df[(df["sales"] > 0) & (df["quantity"] > 0)]
    df["year"] = df["order_date"].dt.year
    df["month"] = df["order_date"].dt.month
    df["year_month"] = df["order_date"].dt.to_period("M").astype(str)
    df["profit_margin"] = df["profit"] / df["sales"]
    return df.reset_index(drop=True)


df = generate_data()

# ----------------------------------------------------------------------------
# 2. Sidebar filters
# ----------------------------------------------------------------------------
st.sidebar.header("Filters")
all_regions = sorted(df["region"].unique())
all_years = [int(y) for y in sorted(df["year"].unique())]
all_cats = sorted(df["category"].unique())

sel_regions = st.sidebar.multiselect("Region", all_regions, default=all_regions)
sel_years = st.sidebar.multiselect("Year", all_years, default=all_years)
sel_cats = st.sidebar.multiselect("Category", all_cats, default=all_cats)
st.sidebar.caption("Data is synthetic (generated by code, fixed seed).")

d = df[df["region"].isin(sel_regions) & df["year"].isin(sel_years) & df["category"].isin(sel_cats)]

st.title("📊 Sales Performance Dashboard")
st.caption("Retail analytics: SQL + Python + statistics. Dataset is synthetic and generated in code.")

if d.empty:
    st.warning("No data for this selection. Pick at least one option in each filter.")
    st.stop()

# ----------------------------------------------------------------------------
# 3. KPI cards
# ----------------------------------------------------------------------------
total_sales = d["sales"].sum()
total_profit = d["profit"].sum()
yearly = d.groupby("year")["sales"].sum()
yoy = f"{yearly.pct_change().iloc[-1] * 100:.1f}%" if len(yearly) > 1 else "n/a"

c1, c2, c3, c4, c5, c6 = st.columns(6)
c1.metric("Total Sales", f"{total_sales:,.0f}")
c2.metric("Total Profit", f"{total_profit:,.0f}")
c3.metric("Profit Margin", f"{total_profit / total_sales * 100:.1f}%")
c4.metric("Orders", f"{len(d):,}")
c5.metric("Avg Order Value", f"{d['sales'].mean():,.0f}")
c6.metric("Latest YoY Growth", yoy)

tab_over, tab_opp, tab_stats, tab_sql, tab_data = st.tabs(
    ["Overview", "Region Opportunity", "Statistics", "SQL", "Data"])

# ----------------------------------------------------------------------------
# 4. Overview
# ----------------------------------------------------------------------------
with tab_over:
    left, right = st.columns(2)

    m = d.groupby("year_month")["sales"].sum().reset_index()
    m["3-month avg"] = m["sales"].rolling(3).mean()
    fig = go.Figure()
    fig.add_trace(go.Scatter(x=m["year_month"], y=m["sales"], mode="lines+markers", name="Revenue"))
    fig.add_trace(go.Scatter(x=m["year_month"], y=m["3-month avg"], mode="lines", name="3-month avg",
                             line=dict(width=4)))
    fig.update_layout(title="Monthly Revenue", height=380, margin=dict(t=50, b=10))
    left.plotly_chart(fig, width="stretch")

    r = d.groupby("region")["sales"].sum().sort_values(ascending=False)
    fig = go.Figure(go.Bar(x=r.index, y=r.values,
                           marker_color=["#dc2626" if v < r.mean() else "#2563eb" for v in r.values]))
    fig.add_hline(y=r.mean(), line_dash="dash", annotation_text="average region")
    fig.update_layout(title="Revenue by Region (red = below average)", height=380, margin=dict(t=50, b=10))
    right.plotly_chart(fig, width="stretch")

    left, right = st.columns(2)
    c = d.groupby("category")["sales"].sum()
    fig = go.Figure(go.Pie(labels=c.index, values=c.values, hole=0.45))
    fig.update_layout(title="Revenue by Category", height=380, margin=dict(t=50, b=10))
    left.plotly_chart(fig, width="stretch")

    dm = d.groupby("discount")["profit_margin"].mean() * 100
    fig = go.Figure(go.Bar(x=[f"{int(x * 100)}%" for x in dm.index], y=dm.values))
    fig.update_layout(title="Average Profit Margin by Discount Level", yaxis_title="Profit margin %",
                      height=380, margin=dict(t=50, b=10))
    right.plotly_chart(fig, width="stretch")

    heat = d.pivot_table(index="region", columns="category", values="sales", aggfunc="sum")
    fig = go.Figure(go.Heatmap(z=heat.values, x=heat.columns, y=heat.index, colorscale="Blues",
                               text=(heat.values / 1000).round(0), texttemplate="%{text}K"))
    fig.update_layout(title="Revenue Heatmap: Region x Category", height=380, margin=dict(t=50, b=10))
    st.plotly_chart(fig, width="stretch")

# ----------------------------------------------------------------------------
# 5. Region opportunity (uses all regions, respects Year and Category filters)
# ----------------------------------------------------------------------------
with tab_opp:
    base = df[df["year"].isin(sel_years) & df["category"].isin(sel_cats)]
    st.write("**Method:** find the average revenue per region. Regions below that average are "
             "'underperforming'. Opportunity = extra revenue if they reach the average. "
             "(Uses all regions; only the Year and Category filters apply here.)")
    rev = base.groupby("region")["sales"].sum()
    avg_region = rev.mean()
    under = rev[rev < avg_region]
    gap = avg_region - under
    total = rev.sum()
    if gap.empty:
        st.info("No region is below average for this selection.")
    else:
        opp = pd.DataFrame({
            "current_revenue": under,
            "average_region_revenue": avg_region,
            "gap_to_average": gap,
            "gap_pct_of_region": gap / under * 100,
        }).round(2)
        st.dataframe(opp, width="stretch")
        a, b, c_ = st.columns(3)
        a.metric("Full gap closed", f"{gap.sum() / total * 100:.1f}%")
        b.metric("50% of gap closed", f"{gap.sum() * 0.5 / total * 100:.1f}%")
        c_.metric("25% of gap closed", f"{gap.sum() * 0.25 / total * 100:.1f}%")
        st.caption("Percentages are extra revenue as a share of current total revenue.")

# ----------------------------------------------------------------------------
# 6. Statistics
# ----------------------------------------------------------------------------
with tab_stats:
    st.subheader("Descriptive statistics")
    cols = ["sales", "profit", "quantity", "discount"]
    desc = d[cols].describe().T
    desc["median"] = d[cols].median()
    st.dataframe(desc[["mean", "median", "std", "min", "max"]].round(2), width="stretch")

    st.subheader("Inferential statistics")
    groups = [g["sales"].values for _, g in d.groupby("region") if len(g) > 1]
    if len(groups) >= 2:
        f_stat, p_anova = stats.f_oneway(*groups)
        st.write(f"**ANOVA** (order value across regions): F = {f_stat:.2f}, p = {p_anova:.4f}")
    else:
        st.write("ANOVA needs at least two regions selected.")

    if d["discount"].nunique() > 1:
        r_, p_ = stats.pearsonr(d["discount"], d["profit_margin"])
        st.write(f"**Correlation** discount vs profit margin: r = {r_:.3f}, p = {p_:.4g}")

    hi = d.loc[d["discount"] >= 0.20, "profit_margin"]
    lo = d.loc[d["discount"] < 0.20, "profit_margin"]
    if len(hi) > 1 and len(lo) > 1:
        t_stat, p_t = stats.ttest_ind(hi, lo, equal_var=False)
        st.write(f"**t-test** profit margin, discount >= 20% vs < 20%: t = {t_stat:.2f}, p = {p_t:.4g}")
        st.write(f"Mean margin: high discount {hi.mean():.2%}, low discount {lo.mean():.2%}")

# ----------------------------------------------------------------------------
# 7. SQL
# ----------------------------------------------------------------------------
with tab_sql:
    st.write("These queries run on the filtered data using SQLite (inside Python).")
    conn = sqlite3.connect(":memory:")
    d_sql = d.copy()
    d_sql["order_date"] = d_sql["order_date"].dt.strftime("%Y-%m-%d")
    d_sql.to_sql("sales", conn, index=False, if_exists="replace")

    queries = {
        "Revenue, profit and orders by region": """
SELECT region,
       ROUND(SUM(sales), 2)  AS revenue,
       ROUND(SUM(profit), 2) AS profit,
       COUNT(*)              AS orders,
       ROUND(AVG(sales), 2)  AS avg_order_value
FROM sales
GROUP BY region
ORDER BY revenue DESC""",
        "Year-over-year growth by region (window function)": """
WITH yr AS (
    SELECT region, year, SUM(sales) AS revenue
    FROM sales GROUP BY region, year
)
SELECT region, year, ROUND(revenue, 2) AS revenue,
       ROUND(100.0 * (revenue - LAG(revenue) OVER (PARTITION BY region ORDER BY year))
             / LAG(revenue) OVER (PARTITION BY region ORDER BY year), 2) AS yoy_growth_pct
FROM yr
ORDER BY region, year""",
        "Category performance": """
SELECT category,
       ROUND(SUM(sales), 2) AS revenue,
       ROUND(SUM(profit), 2) AS profit,
       ROUND(100.0 * SUM(profit) / SUM(sales), 2) AS margin_pct
FROM sales GROUP BY category ORDER BY revenue DESC""",
    }
    for title, sql in queries.items():
        st.markdown(f"**{title}**")
        st.code(sql.strip(), language="sql")
        st.dataframe(pd.read_sql_query(sql, conn), width="stretch")

# ----------------------------------------------------------------------------
# 8. Data
# ----------------------------------------------------------------------------
with tab_data:
    st.write(f"{len(d):,} rows after filters (showing first 500).")
    st.dataframe(d.head(500), width="stretch")
    st.download_button("Download filtered data (CSV)",
                       d.drop(columns=["year_month"]).to_csv(index=False).encode("utf-8"),
                       file_name="sales_filtered.csv", mime="text/csv")
